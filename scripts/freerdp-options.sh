  n="$(basename "$d" | tr '[:lower:]' '[:upper:]')"
  opts+=("-DCHANNEL_${n}=OFF")
done
opts+=(-DCHANNEL_DRDYNVC=ON -DCHANNEL_DRDYNVC_CLIENT=ON)
