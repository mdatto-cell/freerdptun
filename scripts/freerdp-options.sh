 -DWITH_SERVER_INTERFACE=OFF -DWITH_SAMPLE=OFF -DWITH_PROXY=OFF -DWITH_PROXY_APP=OFF
 -DWITH_SHADOW=OFF -DWITH_SHADOW_SUBSYSTEM=OFF -DWITH_SERVER_SHADOW_CLI=OFF
 -DWITH_X11=OFF -DWITH_WAYLAND=OFF -DWITH_SDL=OFF -DWITH_CLIENT_SDL=OFF
 -DWITH_FFMPEG=OFF -DWITH_SWSCALE=OFF -DWITH_CAIRO=OFF -DWITH_AOM=OFF
 -DWITH_KRB5=OFF -DWITH_FUSE=OFF -DWITH_CUPS=OFF -DWITH_PCSC=OFF -DWITH_PKCS11=OFF
 -DWITH_ALSA=OFF -DWITH_PULSE=OFF -DWITH_OSS=OFF -DWITH_OPUS=OFF
